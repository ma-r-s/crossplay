create or replace function is_allowed() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from allowed_users
    where email = coalesce(auth.jwt() ->> 'email', '')
  )
$$;

create or replace function touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end
$$;
drop trigger if exists cards_touch on cards;
create trigger cards_touch before update on cards
  for each row execute function touch_updated_at();

-- Mario's inbox: every open blocker that needs him, with its card.
create or replace view inbox as
  select b.id as blocker_id, b.n, c.id as card_id, c.title, c.app, c.kind, c.body,
         c.state, b.ask, b."default", b.created_at
  from blockers b join cards c on c.id = b.card_id
  where b.open and b.need = 'mario'
  order by b.created_at;

alter table cards enable row level security;
alter table blockers enable row level security;
alter table history enable row level security;
alter table owners enable row level security;
alter table claims enable row level security;
alter table sessions enable row level security;
alter table allowed_users enable row level security;

do $$
declare t text;
begin
  foreach t in array array['cards', 'blockers', 'history', 'owners', 'claims', 'sessions'] loop
    execute format('drop policy if exists allowed_all on %I', t);
    execute format(
      'create policy allowed_all on %I for all to authenticated using (is_allowed()) with check (is_allowed())', t);
  end loop;
end $$;

drop policy if exists allowed_read_self on allowed_users;
create policy allowed_read_self on allowed_users for select to authenticated
  using (email = coalesce(auth.jwt() ->> 'email', ''));

