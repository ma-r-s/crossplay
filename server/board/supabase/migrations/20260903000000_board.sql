-- The board: one card per piece of work, its blockers, who owns what, and
-- Mario's inbox as a view. Written by the `board` CLI with the service key,
-- by the site's report function with the service key, and read by Mario's
-- inbox page as an authenticated user. Nobody else has any access: RLS is on
-- everywhere and the only policy admits the emails in allowed_users.

create table if not exists cards (
  id bigint generated by default as identity primary key,
  title text not null,
  app text not null default 'general',
  kind text not null default 'task' check (kind in ('bug', 'feature', 'task')),
  body text not null default '',
  state text not null default 'reported'
    check (state in ('reported', 'triaged', 'working', 'review', 'merged', 'released', 'done', 'parked')),
  source text not null default 'session' check (source in ('session', 'site', 'import')),
  tree text,
  branch text,
  session text,
  device text,
  version text,
  reporter_email text,
  photo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists blockers (
  id bigint generated by default as identity primary key,
  card_id bigint not null references cards (id) on delete cascade,
  n integer not null,
  need text not null check (need in ('desk', 'design', 'info', 'mario', 'device', 'other')),
  ask text not null,
  "default" text not null default '',
  open boolean not null default true,
  by_session text,
  answer_choice text,
  answer_note text,
  answered_at timestamptz,
  created_at timestamptz not null default now(),
  unique (card_id, n)
);

create table if not exists history (
  id bigint generated by default as identity primary key,
  card_id bigint not null references cards (id) on delete cascade,
  at timestamptz not null default now(),
  what text not null
);

create table if not exists owners (
  app text primary key,
  session text,
  tree text,
  since timestamptz not null default now()
);

create table if not exists claims (
  name text primary key check (name in ('orchestrator', 'integrator')),
  session text not null,
  display_name text,
  since timestamptz not null default now()
);

create table if not exists sessions (
  id text primary key,
  cwd text,
  card_id bigint references cards (id) on delete set null,
  started_at timestamptz not null default now(),
  last_seen timestamptz not null default now()
);

-- Who may read and write from a browser. The CLI and the site function use
-- the service key and bypass this; the inbox page signs in by magic link and
-- must be one of these.
create table if not exists allowed_users (
  email text primary key
);
