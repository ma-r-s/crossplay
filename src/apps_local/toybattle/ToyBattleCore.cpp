// 15 bases in a 5x3 lattice, an H.Q. at each end, and the eight cells of the
// lattice as regions. See the header for why this is ours and not Repos'.
constexpr Terrain buildProvingGround() {
  Terrain t{};
  t.name = "PROVING GROUND";
  t.baseCount = 15;
  t.hqCount = 2;
  t.hqSeat[0] = 0;
  t.hqSeat[1] = 1;
  t.medalsObjective = 7;

  // Rows of 5, left to right, top row first.
  for (int row = 0; row < 3; ++row) {
    for (int col = 0; col < 5; ++col) {
      const int b = row * 5 + col;
      t.x[b] = static_cast<uint16_t>(200 + col * 150);
      t.y[b] = static_cast<uint16_t>(200 + row * 300);
    }
  }
  t.x[15] = 60;
  t.y[15] = 500;  // seat 0's H.Q., left
  t.x[16] = 940;
  t.y[16] = 500;  // seat 1's H.Q., right

  int e = 0;
  for (int row = 0; row < 3; ++row) {
    for (int col = 0; col < 4; ++col) {
      t.edges[e++] = Edge{static_cast<uint8_t>(row * 5 + col), static_cast<uint8_t>(row * 5 + col + 1)};
    }
  }
  for (int row = 0; row < 2; ++row) {
    for (int col = 0; col < 5; ++col) {
      t.edges[e++] = Edge{static_cast<uint8_t>(row * 5 + col), static_cast<uint8_t>((row + 1) * 5 + col)};
    }
  }
  t.edges[e++] = Edge{15, 0};
  t.edges[e++] = Edge{15, 5};
  t.edges[e++] = Edge{15, 10};
  t.edges[e++] = Edge{16, 4};
  t.edges[e++] = Edge{16, 9};
  t.edges[e++] = Edge{16, 14};
  t.edgeCount = static_cast<uint8_t>(e);

  int r = 0;
  for (int row = 0; row < 2; ++row) {
    for (int col = 0; col < 4; ++col) {
      const int tl = row * 5 + col;
      t.regions[r].bases =
          (uint32_t{1} << tl) | (uint32_t{1} << (tl + 1)) | (uint32_t{1} << (tl + 5)) | (uint32_t{1} << (tl + 6));
      t.regions[r].medals = 2;
      ++r;
    }
  }
  t.regionCount = static_cast<uint8_t>(r);

  // Every special base kind, all on one board. No terrain Repos printed does
  // that -- each of theirs uses a single kind throughout -- but nothing in the
  // rules forbids it, and it gives the tests one place to exercise all seven.
  // Bases 4 and 9 carry the two placement restrictions because they are the
  // only two no other test places on.
  t.special[2] = static_cast<uint8_t>(Special::Recall);
  t.special[3] = static_cast<uint8_t>(Special::Exhume);
  t.special[7] = static_cast<uint8_t>(Special::Draw);
  t.special[8] = static_cast<uint8_t>(Special::Suppress);
  t.special[12] = static_cast<uint8_t>(Special::Shove);
  t.special[4] = static_cast<uint8_t>(Special::Nullify);
  t.special[9] = static_cast<uint8_t>(Special::Gate);
  // 6 and 7 only, the way Tropical Pool prints a pair of values on its buoys.
  t.gate[9] = static_cast<uint8_t>((1u << static_cast<int>(Troop::Star)) | (1u << static_cast<int>(Troop::Roxy)));
  return t;
}

