namespace {

void drawTroops(Game& g, int seat, int wanted) {
  const int space = kRackLimit - g.rackSize(seat);
  int n = wanted < space ? wanted : space;
  if (n > g.reserveRemaining(seat)) n = g.reserveRemaining(seat);
  for (int i = 0; i < n; ++i) {
    const Troop drawn = g.reserveAt(seat, kSetAside + g.reserveTaken[seat]);
    ++g.reserveTaken[seat];
    ++g.rack[seat][static_cast<int>(drawn)];
  }
}

// Pops the visible troop off a base. Every removal in this game is of a
// visible troop, so this is the only shape a removal ever takes.
bool popVisible(Game& g, int base, int* outSeat, Troop* outKind) {
  for (int i = g.placementCount - 1; i >= 0; --i) {
    if (g.placeSlot[i] != base) continue;
    *outSeat = tileSeat(g.placeTile[i]);
    *outKind = tileKind(g.placeTile[i]);
    const int tail = g.placementCount - i - 1;
    if (tail > 0) {
      memmove(&g.placeSlot[i], &g.placeSlot[i + 1], static_cast<size_t>(tail));
      memmove(&g.placeTile[i], &g.placeTile[i + 1], static_cast<size_t>(tail));
    }
    --g.placementCount;
    return true;
  }
  return false;
}

void endGame(Game& g, int winnerSeat, Ending why) {
  g.phase = static_cast<uint8_t>(Phase::GameOver);
  g.winner = static_cast<uint8_t>(winnerSeat);
  g.ending = static_cast<uint8_t>(why);
}

// Regions fall the instant their last base is held, for either seat, after any
// change to the board -- including one that merely uncovers a buried tile.
void settleRegions(Game& g) {
  const Terrain& b = g.board();
  for (int seat = 0; seat < kSeats; ++seat) {
    const uint32_t mine = g.occupiedBy(seat);
    for (int r = 0; r < b.regionCount; ++r) {
      const uint16_t bit = static_cast<uint16_t>(1u << r);
      if (g.regionsTaken & bit) continue;
      if ((mine & b.regions[r].bases) != b.regions[r].bases) continue;
      g.regionsTaken = static_cast<uint16_t>(g.regionsTaken | bit);
      g.medals[seat] = static_cast<uint8_t>(g.medals[seat] + b.regions[r].medals);
      if (g.medals[seat] >= b.medalsObjective && g.currentPhase() == Phase::Playing) {
        endGame(g, seat, Ending::MedalsObjective);
      }
    }
  }
}

// Picks a troop from a rack at random, the way "point at one without looking"
// picks one. Returns kTroopKinds when the rack is empty.
int blindPick(Game& g, int seat, uint32_t salt) {
  const int held = g.rackSize(seat);
  if (held == 0) return kTroopKinds;
  int pick =
      static_cast<int>(mix32(g.seed ^ salt ^ (static_cast<uint32_t>(g.rngTick) << 16)) % static_cast<uint32_t>(held));
  ++g.rngTick;
  for (int k = 0; k < kTroopKinds; ++k) {
    if (pick < g.rack[seat][k]) return k;
    pick -= g.rack[seat][k];
  }
  return kTroopKinds;
}

// The special base under a placement, applied after every troop effect of the
// turn. Two rules govern all of them: only visible troops can be interacted
// with, and an effect that would push a rack past 8 cannot be applied at all
// (the aid is explicit that it is refused rather than clamped).
//
// `placed` is the slot whose base is firing, so Recall can exclude the troop
// that just landed there.
bool applyBaseEffect(Game& g, int seat, const Step& s, int placed) {
  const Terrain& b = g.board();
  const Special what = b.specialAt(placed);
  const int foe = other(seat);

  switch (what) {
    case Special::None:
    case Special::Gate:
    case Special::Nullify:
      return false;  // restrictions, not effects: nothing fires afterwards

    case Special::Draw:
      if (g.rackSize(seat) >= kRackLimit) return false;
      if (g.reserveRemaining(seat) == 0) return false;
      drawTroops(g, seat, 1);
      return true;

    case Special::Exhume: {
      if (g.rackSize(seat) >= kRackLimit) return false;
      if (s.baseKind >= kTroopKinds) return false;
      if (g.discarded[seat][s.baseKind] == 0) return false;
      --g.discarded[seat][s.baseKind];
      ++g.rack[seat][s.baseKind];
      return true;
    }

    case Special::Recall: {
      if (g.rackSize(seat) >= kRackLimit) return false;
      if (s.baseFrom >= b.baseCount) return false;
      if (s.baseFrom == placed) return false;  // "one of your OTHER troops"
      if (g.occupantSeat(s.baseFrom) != seat) return false;
      int who = 0;
      Troop what2 = Troop::Kwak;
      if (!popVisible(g, s.baseFrom, &who, &what2)) return false;
      ++g.rack[seat][static_cast<int>(what2)];
      settleRegions(g);
      return true;
    }

    case Special::Shove: {
      // An adjacent enemy troop, moved to a base beside where it stood,
      // ignoring the placement rules entirely -- so strength, ownership and
      // connection all stop mattering for this one move.
      if (s.baseFrom >= b.baseCount || s.baseTo >= b.baseCount) return false;
      if (!(b.adj[placed] & (uint64_t{1} << s.baseFrom))) return false;
      if (!(b.adj[s.baseFrom] & (uint64_t{1} << s.baseTo))) return false;
      if (g.occupantSeat(s.baseFrom) != foe) return false;
      int who = 0;
      Troop what2 = Troop::Kwak;
      if (!popVisible(g, s.baseFrom, &who, &what2)) return false;
      g.placeSlot[g.placementCount] = s.baseTo;
      g.placeTile[g.placementCount] = packTile(who, what2);
      ++g.placementCount;
      settleRegions(g);
      return true;
    }

    case Special::Suppress: {
      const int picked = blindPick(g, foe, 0xB1F1E1D0u);
      if (picked >= kTroopKinds) return false;
      g.frozenKind[foe] = static_cast<uint8_t>(picked);
      return true;
    }
  }
  return false;
}

bool applyStep(Game& g, int seat, const Step& s, bool chainContinues) {
  const Terrain& b = g.board();
  const Troop kind = static_cast<Troop>(s.kind);
  if (s.kind >= kTroopKinds) return false;

  // Troop effects do not happen on a Station Metal-X base, so claiming one
  // there is not a legal move rather than a silent no-op.
  if (g.specialBases && b.specialAt(s.slot) == Special::Nullify && s.useEffect) return false;
  // And the base flag has to name a base that actually has something to fire.
  if (s.useBase && !(g.specialBases && firesAfterPlacement(b.specialAt(s.slot)))) return false;

  // A Cap'n's effect *is* the extra placement, so the flag and the presence of
  // a following step have to agree. Anything else is a move that means two
  // things at once.
  if (chainContinues && !(kind == Troop::Capn && s.useEffect)) return false;
  if (!chainContinues && kind == Troop::Capn && s.useEffect) return false;
  if (s.useEffect && !hasEffect(kind)) return false;

  const bool waiver = s.useEffect && kind == Troop::Hook;
  if (!g.canPlaceHere(seat, s.slot, kind, waiver)) return false;

  --g.rack[seat][s.kind];
  g.placeSlot[g.placementCount] = s.slot;
  g.placeTile[g.placementCount] = packTile(seat, kind);
  ++g.placementCount;

  if (b.isHq(s.slot)) {
    endGame(g, seat, Ending::HqCaptured);
    return true;
  }

  settleRegions(g);
  if (g.currentPhase() != Phase::Playing) return true;

  if (!s.useEffect) return true;

  switch (kind) {
    case Troop::Skully:
      drawTroops(g, seat, 2);
      break;
    case Troop::Star:
      drawTroops(g, seat, 1);
      break;
    case Troop::Hook:
      break;  // the waiver was the effect, and it was spent on the placement
    case Troop::Capn:
      break;  // the extra placement is the next step
    case Troop::Jumbo: {
      // One section of path, and only a visible enemy troop.
      if (s.target == kNoSlot) return false;
      if (s.target >= b.baseCount) return false;
      if (!(b.adj[s.slot] & (uint64_t{1} << s.target))) return false;
      if (g.occupantSeat(s.target) != other(seat)) return false;
      int victimSeat = 0;
      Troop victimKind = Troop::Kwak;
      if (!popVisible(g, s.target, &victimSeat, &victimKind)) return false;
      ++g.discarded[victimSeat][static_cast<int>(victimKind)];
      settleRegions(g);
      break;
    }
    case Troop::XB42: {
      const int foe = other(seat);
      const int picked = blindPick(g, foe, 0xB5000000u);
      if (picked < kTroopKinds) {
        --g.rack[foe][picked];
        ++g.discarded[foe][picked];
        // A suppressed troop that has just been shot off the rack cannot stay
        // suppressed: the mark would otherwise freeze a kind the seat is free
        // to draw again later.
        if (g.frozenKind[foe] == static_cast<uint8_t>(picked) && g.rack[foe][picked] == 0) {
          g.frozenKind[foe] = kNoSlot;
        }
      }
      break;
    }
    case Troop::Kwak:
    case Troop::Roxy:
      break;  // rejected above; no effect to apply
  }
  return true;
}

bool tryApply(Game& g, const Move& move) {
  if (g.currentPhase() != Phase::Playing) return false;
  const int seat = g.turn;

  if (move.kind == Move::Kind::Draw) {
    if (move.stepCount != 0) return false;
    if (!g.canDraw(seat)) return false;
    drawTroops(g, seat, 2);
  } else {
    if (move.stepCount < 1 || move.stepCount > kMaxChain) return false;
    for (int i = 0; i < move.stepCount; ++i) {
      const bool chainContinues = i + 1 < move.stepCount;
      if (!applyStep(g, seat, move.steps[i], chainContinues)) return false;
      // A win mid-chain ends the game there: the rest of the Cap'n's chain
      // never happens.
      if (g.currentPhase() != Phase::Playing) return true;
    }

    // "First apply all the effects of Troops you just placed, then apply any
    // special base effects." So a Cap'n chain runs both troop effects before
    // either base fires, and the bases then fire in the order they were
    // occupied. Getting this backwards is a real difference: a base that
    // returns a troop to your rack changes what the extra placement could
    // have been.
    for (int i = 0; i < move.stepCount; ++i) {
      const Step& s = move.steps[i];
      if (!s.useBase) continue;
      if (!applyBaseEffect(g, seat, s, s.slot)) return false;
      if (g.currentPhase() != Phase::Playing) return true;
    }
  }

  // The suppressed troop goes back on the rack at the end of the turn it sat
  // out. Clearing the mover's own mark here is exactly that: the enemy set it
  // during their turn, this turn happened without it, and now it is spent.
  g.frozenKind[seat] = kNoSlot;

  g.turn = static_cast<uint8_t>(other(seat));
  if (!g.hasAnyLegalMove(g.turn)) {
    const int stuck = g.turn;
    const int foe = other(stuck);
    // Most medals, and a tie goes against whoever could not act.
    const int winnerSeat = g.medals[stuck] > g.medals[foe] ? stuck : foe;
    endGame(g, winnerSeat, Ending::Stuck);
  }
  return true;
}

}  // namespace

bool Game::isLegal(const Move& move) const {
  Game trial = *this;
  return tryApply(trial, move);
}

bool Game::apply(const Move& move) {
  Game trial = *this;
  if (!tryApply(trial, move)) return false;
  *this = trial;
  return true;
}

