#!/bin/sh
# Live's arithmetic on a laptop: the interval clamp, the capped backoff, the
# clock plausibility floor and the one wake rule.
#
#   host-tests/live/run.sh
#
# Nothing here touches a card, a radio or a panel, which is the point: the
# failure the backoff exists to prevent is a battery three weeks out, and the
# due-now rule only misbehaves on the sleep AFTER the one you were watching.
# Neither is observable by looking at a device.
set -e
cd "$(dirname "$0")"
BUILD_DIR="${TMPDIR:-/tmp}/$(basename "${CXX:-c++}")-live-tests-$(cd ../.. && pwd | cksum | cut -d" " -f1)"
mkdir -p "$BUILD_DIR"

# THE SERVICE'S THREE NUMBERS, read out of the service rather than typed here.
#
# The reader holds a copy of all three: the clamp it applies to X-Next-Wake and
# the interval it seeds itself with before the service has ever spoken. They are
# two copies of one fact and one of them drifted -- six hours against a day --
# and nothing anywhere could have noticed, because neither side had the other's
# number. Generated, so a change on either side fails this run.
python3 - ../../server/fridge-bridge/bridge/store.py > "$BUILD_DIR/service_limits.generated.h" <<'PY'
import ast
import sys

tree = ast.parse(open(sys.argv[1]).read())
want = {"DEFAULT_INTERVAL_S", "MIN_INTERVAL_S", "MAX_INTERVAL_S"}
found = {}
for node in tree.body:
    if not isinstance(node, ast.Assign):
        continue
    for target in node.targets:
        if isinstance(target, ast.Name) and target.id in want:
            found[target.id] = int(eval(compile(ast.Expression(node.value), "<s>", "eval"), {}, {}))
missing = want - set(found)
if missing:
    sys.exit("live: store.py no longer defines %s, so the reader's copy is unchecked" % ", ".join(sorted(missing)))

print("// Generated by host-tests/live/run.sh from server/fridge-bridge/bridge/store.py.")
for name, value in sorted(found.items()):
    print("constexpr long kService%s = %d;" % (name.title().replace("_", ""), value))
PY

"${CXX:-c++}" -std=c++17 -O1 -Wall -Wextra -Werror -I"$BUILD_DIR" \
  ../../src/apps_local/live/LiveCore.cpp \
  test_live.cpp -o "$BUILD_DIR/test_live"
"$BUILD_DIR/test_live"

# EVERY WAY INTO DEEP SLEEP CARRIES LIVE'S ALARM (card #620).
#
# The arithmetic above is worth nothing if a sleep path does not call it, and
# that is exactly how Mario's fridge missed its 02:00: two re-sleep paths in
# main.cpp armed kTimerWakeMicros, which is 0 on every release env, and one
# bump disarmed Live. main.cpp cannot link on a laptop, so it is read. Every
# startDeepSleepArmed() call must pass Live's number: enterDeepSleep's
# timerMicros, the timer wake's nextWake, or resleepTimerMicros(). A bare
# kTimerWakeMicros is the bug.
python3 - ../../src/main.cpp <<'PY'
import re
import sys

# Comments stripped first, so a sentence naming the call is not read as one;
# braces excluded, so the definition is not read as a call.
src = re.sub(r"//[^\n]*", "", open(sys.argv[1]).read())
calls = re.findall(r"startDeepSleepArmed\(([^;{}]*)\);", src)
bad = [c for c in calls if c.strip() == "kTimerWakeMicros"]
fails = 0
if len(calls) != 4:
    print("FAIL live  found %d startDeepSleepArmed calls in main.cpp, expected 4 (enterDeepSleep, the timer wake, and the two re-sleeps); read the new one and add it here" % len(calls))
    fails += 1
for c in bad:
    print("FAIL live  main.cpp sleeps with startDeepSleepArmed(%s): 0 on a release build, so Live's alarm is dropped (card #620)" % c.strip())
    fails += 1
allowed = ("timerMicros", "resleepTimerMicros()", "nextWake")
for c in calls:
    if c.strip() in bad:
        continue
    if not any(a in c for a in allowed):
        print("FAIL live  main.cpp sleeps with startDeepSleepArmed(%s), which is not Live's number" % c.strip())
        fails += 1
m = re.search(r"resleepTimerMicros\(\)\s*\{(.*?)\n\}", src, re.S)
if not m or "live::engine::resleepSeconds()" not in m.group(1):
    print("FAIL live  resleepTimerMicros() no longer asks live::engine::resleepSeconds()")
    fails += 1
print("live-sleep-paths: %d calls, %d failed" % (len(calls), fails))
sys.exit(1 if fails else 0)
PY

# THE ALARM REACHES A REAL TIMER, through every layer under main.cpp.
#
# CrossPoint 2.0 gave HalPowerManager::startDeepSleep a second argument of its
# own, `bool wakeOnHeldButton`, in the slot where this fork passes Live's
# `uint64_t timerWakeMicros`. Either call shape compiles against the other
# declaration: upstream's `startDeepSleep(gpio, true)` against ours arms a
# ONE-MICROSECOND timer (the device wakes the instant it sleeps), and ours
# against theirs turns Live's alarm into "wake on a held button" with no timer
# at all. Nothing on a laptop can run deep sleep, so the chain is read: the
# declaration keeps the timer in the second slot and deletes the bool-only
# shape, the definition hands the timer to the SDK on BOTH of its exits, the
# SDK arms the RTC with it, and main.cpp passes Live's number in the timer
# slot rather than anywhere else.
python3 - ../../lib/hal/HalPowerManager.h ../../lib/hal/HalPowerManager.cpp ../../src/main.cpp \
  ../../freeink-sdk/libs/hardware/PowerManager/src/PowerManager.cpp <<'PY'
import re
import sys

def code(path):
    return re.sub(r"//[^\n]*", "", open(path).read())

hdr, cpp, main, sdk = (code(p) for p in sys.argv[1:5])
fails = 0

def check(ok, what):
    global fails
    if not ok:
        fails += 1
        print("FAIL live  " + what)

check(re.search(r"void\s+startDeepSleep\(\s*HalGPIO&\s*gpio,\s*uint64_t\s+timerWakeMicros\s*=\s*0,\s*bool\s+wakeOnHeldButton\s*=\s*false\s*\)\s*const;", hdr) is not None,
      "HalPowerManager.h no longer declares startDeepSleep(gpio, uint64_t timerWakeMicros = 0, bool wakeOnHeldButton = false)")
check(re.search(r"void\s+startDeepSleep\(\s*HalGPIO&\s*gpio,\s*bool\s+\w*\s*\)\s*const\s*=\s*delete;", hdr) is not None,
      "HalPowerManager.h no longer deletes startDeepSleep(gpio, bool): upstream's call shape would compile into a 1us timer")

m = re.search(r"void\s+HalPowerManager::startDeepSleep\(\s*HalGPIO&\s*gpio,\s*const\s+uint64_t\s+timerWakeMicros,\s*const\s+bool\s+wakeOnHeldButton\s*\)\s*const\s*\{(.*?)\n\}", cpp, re.S)
check(m is not None, "HalPowerManager::startDeepSleep(gpio, timerWakeMicros, wakeOnHeldButton) definition not found")
body = m.group(1) if m else ""
check(re.search(r"deepSleepUntilPowerButtonOrTimer\(\s*timerWakeMicros\s*\)", body) is not None,
      "the ordinary exit no longer hands timerWakeMicros to deepSleepUntilPowerButtonOrTimer")
held = re.search(r"if\s*\(\s*wakeOnHeldButton\s*\)\s*\{(.*?)\}", body, re.S)
check(held is not None and re.search(r"armTimerWakeup\(\s*timerWakeMicros\s*\).*deepSleep\(\)", held.group(1), re.S) is not None,
      "the wakeOnHeldButton exit sleeps without arming timerWakeMicros first")

timer = re.search(r"void\s+PowerManager::armTimerWakeup\(\s*const\s+uint64_t\s+micros\s*\)\s*\{(.*?)\n\}", sdk, re.S)
check(timer is not None and "esp_sleep_enable_timer_wakeup(micros)" in timer.group(1),
      "freeink-sdk PowerManager::armTimerWakeup no longer arms esp_sleep_enable_timer_wakeup(micros)")
both = re.search(r"void\s+PowerManager::deepSleepUntilPowerButtonOrTimer\(\s*const\s+uint64_t\s+micros\s*\)\s*\{(.*?)\n\}", sdk, re.S)
check(both is not None and "armTimerWakeup(micros)" in both.group(1) and "deepSleep()" in both.group(1),
      "freeink-sdk deepSleepUntilPowerButtonOrTimer no longer arms the timer before sleeping")

armed = re.search(r"static\s+void\s+startDeepSleepArmed\((.*?)\)\s*\{(.*?)\n\}", main, re.S)
check(armed is not None, "main.cpp startDeepSleepArmed not found")
if armed:
    calls = re.findall(r"powerManager\.startDeepSleep\(([^;]*)\);", armed.group(2))
    device = [c for c in calls if c.count(",") >= 1]
    check(len(device) == 1 and [a.strip() for a in device[0].split(",")][:2] == ["gpio", "timerMicros"],
          "startDeepSleepArmed does not pass timerMicros as startDeepSleep's second argument: %s" % calls)
print("live-timer-chain: %d failed" % fails)
sys.exit(1 if fails else 0)
PY
