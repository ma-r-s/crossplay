#!/bin/bash
# Vendored artwork: does the thing it was generated from still exist, and does
# its licence still ship?
#
# Art in this fork is rasterised at authoring time into a committed C header.
# The header is what builds; the SVGs, the manifest and the generator are only
# needed to change it. That asymmetry is the hazard: delete the inputs and
# every build stays green, every test stays green, and the only thing lost is
# the ability to regenerate -- and, when the inputs carried a LICENSE, the
# notice the fork is obliged to ship.
#
# Both halves of that happened. Chess's ChessPieces.h said its MIT licence
# "travels with the SVGs in assets_local/pieces/celtic/", a directory that was
# never on this branch; tools_local/chess/gen_chess_pieces.py read its inputs
# from the same missing path. Solitaire's SolitaireSuits.h named a generator at
# tools/gen_suit_icons.sh that does not exist, and -- having outlived the art it
# described -- credited the one candidate set that was rejected.
#
# Nothing here is a list to keep up to date. Each check DISCOVERS its subjects:
# every generator under tools_local/, every licence file beside vendored art,
# every "Generated by" banner an app header carries.
#
#   host-tests/vendored/run.sh
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"

python3 - "$ROOT" <<'PY'
import os
import re
import subprocess
import sys

root = sys.argv[1]
checks = 0
failed = 0


def check(ok, label, detail=""):
    global checks, failed
    checks += 1
    if not ok:
        failed += 1
        print(f"FAIL vendored  {label}" + (f": {detail}" if detail else ""))


def skip(label):
    """Locally a missing submodule is information; in CI it is a failure.

    The only thing these checks need that a checkout may lack is a submodule,
    and the distribution is lopsided: check.sh's throwaway worktree
    deliberately does NOT recurse (pulling lucide cost 237s of a 244s run), so
    a local --committed run skips them every time, while CI checks out
    submodules: recursive in the build job that runs host-tests and so has
    them every time. Without this guard the five checks would run ONLY in CI,
    and the guard against "this suite never ran" would itself be unguarded --
    the same defect wearing the other face. Modelled on host-tests/release.
    """
    if os.environ.get("CI"):
        check(False, f"{label} (a skip is a failure in CI: submodules are checked out here)")
    else:
        print(f"  SKIP vendored  {label}")


tracked = [t for t in subprocess.run(["git", "-C", root, "ls-files", "-z"],
                                     capture_output=True, text=True).stdout.split("\0") if t]

# Every file on disk, not only the tracked ones: freeink-sdk/ is a submodule, so
# git ls-files here does not list a single file inside it, and the SDK is where
# half the generators named by a banner actually live.
SKIP_DIRS = {".git", ".pio", ".pio-cache", "node_modules", "fs_agent", "fs_mario",
             "qa-artifacts", "emulator", "pyodide", "libdeps", ".venv", ".venv-study"}
ALL_FILES = []
for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
    base = os.path.relpath(dirpath, root)
    for name in filenames:
        ALL_FILES.append(name if base == "." else os.path.join(base, name))

# Submodules are a property of the CHECKOUT, not of this repository. The gate
# builds in a throwaway worktree that initialises freeink-sdk but not the lucide
# submodule NESTED inside it, and five generators read their SVGs from there --
# so asserting those paths exist fails on a tree with nothing wrong with it.
# Discovered from every .gitmodules in the tree, root and nested, because the
# one that caused this is not in the root's.
SUBMODULES = []
for dirpath, dirnames, filenames in os.walk(root):
    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
    if ".gitmodules" not in filenames:
        continue
    base = os.path.relpath(dirpath, root)
    with open(os.path.join(dirpath, ".gitmodules"), encoding="utf-8", errors="replace") as f:
        for m in re.finditer(r"^\s*path\s*=\s*(\S+)", f.read(), re.M):
            SUBMODULES.append(m.group(1) if base == "." else os.path.join(base, m.group(1)))


def absent_submodule(rel_path):
    """The submodule this path needs, if that submodule is not checked out."""
    for sm in SUBMODULES:
        if rel_path == sm or rel_path.startswith(sm + os.sep):
            d = os.path.join(root, sm)
            if not os.path.isdir(d) or not os.listdir(d):
                return sm
    return None


def read(rel):
    with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as f:
        return f.read()


# A path is ours to check only if its first segment is a real top-level
# directory. That is what separates "src/apps_local/solitaire/art" from the
# SDK's own "tools/gen_icons.py" and freetype's "src/base/ftinit.c", both of
# which are relative to a different root and are not this suite's business.
TOP = {d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)) and not d.startswith(".")}


def repo_path(raw):
    p = raw.strip().strip("\"'").rstrip("/")
    if not p or "$" in p or "{" in p or "*" in p:
        return None
    return p if p.split("/")[0] in TOP else None


# ---------------------------------------------------------------------------
# ONE. Every input a generator names must be there. Read from the argument and
# the assignment, not from prose: a generator that cannot run is the failure,
# and its arguments are exactly what it would run on.
# ---------------------------------------------------------------------------
ARG = re.compile(r'--(?:svgdir|manifest)[= ]+"?([^"\s\\]+)"?')
ASSIGN = re.compile(r'^\s*(?:SRC|ART|SVGDIR|MANIFEST)=\s*"?([^"\s#]+)"?', re.M)
PYCHAIN = re.compile(r'ROOT\s*/\s*((?:"[^"]+"\s*/\s*)*"[^"]+")')

generators = [r for r in tracked if r.startswith("tools_local/") and r.endswith((".sh", ".py"))]
check(len(generators) > 10, "the generator sweep found generators to check", f"only {len(generators)}")

for rel in generators:
    body = read(rel)
    wanted = {m.group(1) for m in ARG.finditer(body)}
    wanted |= {m.group(1) for m in ASSIGN.finditer(body)}
    wanted |= {"/".join(re.findall(r'"([^"]+)"', m.group(1))) for m in PYCHAIN.finditer(body)}
    for raw in sorted(wanted):
        p = repo_path(raw)
        if p is None:
            continue
        missing_sm = absent_submodule(p)
        if missing_sm:
            skip(f"{rel} reads {p}: submodule {missing_sm} is not checked out here")
            continue
        check(os.path.exists(os.path.join(root, p)),
              f"{rel} can still find {p}",
              "the generator reads this path and it is not in the tree, so it cannot run")

# ---------------------------------------------------------------------------
# TWO. A licence that ships beside vendored art must be named in the notices
# file, because the bytes it covers are compiled into the firmware where the
# licence file itself cannot travel. THIRD-PARTY-NOTICES.md says that is what
# it is for.
# ---------------------------------------------------------------------------
notices = read("THIRD-PARTY-NOTICES.md")
licences = [r for r in tracked
            if (os.path.dirname(r).startswith("assets_local/")
                or re.fullmatch(r"src/apps_local/[^/]+/art", os.path.dirname(r)))
            and re.match(r"(LICENSE|LICENCE|OFL|COPYING)", os.path.basename(r), re.I)]
check(licences, "there is vendored art with a licence beside it to check",
      "found none -- has vendored art moved, or has a licence file been deleted?")
for rel in licences:
    d = os.path.dirname(rel)
    check(rel in notices or d in notices,
          f"THIRD-PARTY-NOTICES.md names {d}",
          "art with its own licence ships compiled into the firmware; the notice is how it reaches a device")

# ---------------------------------------------------------------------------
# THREE. The banner a generated header carries is the only pointer back to what
# made it. A stale one sends the next person to a file that is not there.
# ---------------------------------------------------------------------------
# Matched by suffix, not by repo root: the SDK's own headers say "Generated by
# tools/gen_icons.py", a path relative to the library that owns it. A banner is
# satisfied by any tracked file it is the tail of, which accepts those and still
# rejects a path nothing in the tree ends with.
BANNER = re.compile(r"Generated by ([A-Za-z0-9_./-]+\.(?:sh|py))")
banners = 0
for rel in tracked:
    if not rel.startswith("src/") or not rel.endswith((".h", ".cpp", ".md")):
        continue
    for named in sorted(set(BANNER.findall(read(rel)))):
        banners += 1
        if any(f == named or f.endswith("/" + named) for f in ALL_FILES):
            checks += 1
            continue
        # Nothing matched. Before calling that a stale banner, rule out the
        # checkout: a banner naming a script inside a submodule that is not
        # here matches nothing for a reason that is not this repo's fault.
        empty = [sm for sm in SUBMODULES
                 if not os.path.isdir(os.path.join(root, sm)) or not os.listdir(os.path.join(root, sm))]
        if empty:
            skip(f"{rel} names {named}, unresolvable: {', '.join(empty)} not checked out")
            continue
        check(False, f"{rel} names a generator that exists ({named})",
              "the header points at a script no path in the tree ends with")
check(banners > 0, "generated headers still carry a 'Generated by' banner",
      "none found -- the banner convention has been renamed and this check has gone blind")

print(f"{checks} checks, {failed} failed")
sys.exit(1 if failed else 0)
PY
