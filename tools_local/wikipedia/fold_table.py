def unescape_tsv(s):
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append(
                {
                    "t": "\t",
                    "n": "\n",
                    "r": "\r",
                    "\\": "\\",
                    "f": "\x0c",
                    "v": "\x0b",
                }.get(n, n)
            )
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def escape_tsv(s):
    return (
        s.replace("\\", "\\\\")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\x0c", "\\f")
        .replace("\x0b", "\\v")
    )


def make_vectors(table):
    table_map = {chr(a): chr(b) for a, b in table}
    inputs = []
    for group in (
        ASCII_TITLES,
        UNDERSCORE_TITLES,
        SPACE_TITLES,
        ACCENT_TITLES,
        GREEK_TITLES,
        CYRILLIC_TITLES,
        PASSTHROUGH_TITLES,
        FUNNY,
    ):
        inputs.extend(group)
    seen = set(inputs)
    assert len(seen) == len(inputs), "duplicate hand-written vector"
    # Fill to VECTOR_COUNT with seeded random titles built from table
    # entries, ASCII words and passthrough scripts, so every table range is
    # exercised beyond the hand-picked names.
    rng = random.Random(20260911)
    words = ["Alpha", "beta", "GAMMA", "delta", "Epsilon", "zeta", "eta", "THETA"]
    cps = [chr(a) for a, _ in table]
    extra = ["日", "本", "語", "京", "한", "글", "ع", "ب"]
    while len(inputs) < VECTOR_COUNT:
        parts = []
        for _ in range(rng.randint(1, 5)):
            kind = rng.random()
            if kind < 0.4:
                parts.append(rng.choice(words))
            elif kind < 0.8:
                parts.append("".join(rng.choice(cps) for _ in range(rng.randint(1, 4))))
            elif kind < 0.9:
                parts.append(
                    "".join(rng.choice(extra) for _ in range(rng.randint(1, 3)))
                )
            else:
                parts.append(rng.choice(["_", "  ", "\t", " _ "]))
        s = rng.choice(["", " ", "_"]).join(parts)
        if s in seen:
            continue
        seen.add(s)
        inputs.append(s)
    assert len(inputs) == VECTOR_COUNT
    return [(s, fold_with(table_map, s)) for s in inputs]


def emit_vectors(vectors, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write("# GENERATED by tools_local/wikipedia/fold_table.py; do not edit.\n")
        f.write(
            "# input<TAB>expected, one per line; \\t \\n \\r \\f \\v \\\\ escape the\n"
        )
        f.write("# characters they name. Lines starting with # are comments.\n")
        for s, e in vectors:
            f.write(f"{escape_tsv(s)}\t{escape_tsv(e)}\n")


def load_vectors(path):
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            line = line.rstrip("\n")
            if not line:
                continue
            a, b = line.split("\t")
            out.append((unescape_tsv(a), unescape_tsv(b)))
    return out


def main():
    table = build_table()
    emit_python(table, os.path.join(HERE, "fold.py"))
    cpp_dir = os.path.join(REPO, "src", "apps_local", "wikipedia")
    os.makedirs(cpp_dir, exist_ok=True)
    emit_cpp(table, os.path.join(cpp_dir, "WikipediaFold.h"))
    vectors = make_vectors(table)
    emit_vectors(vectors, os.path.join(HERE, "fold_vectors.tsv"))
    print(f"table entries: {len(table)}; vectors: {len(vectors)}")
    return 0


