CPP_HEAD = """// GENERATED by tools_local/wikipedia/fold_table.py; do not edit.
//
// The title fold of docs/apps/wikipedia-pack-format.md, "Sort key: the fold".
// tools_local/wikipedia/fold.py is the same procedure in Python and
// tools_local/wikipedia/fold_vectors.tsv proves the two agree. Regenerate
// with: python3 tools_local/wikipedia/fold_table.py
//
// Freestanding: no allocation, no <string>, no locale. The output is never
// longer than the input in bytes (every table replacement is at most as
// long in UTF-8 as the code point it replaces), so an output buffer the size
// of the input always suffices; a smaller one truncates at a character
// boundary and outLen says how much was written.
//
// clang-format off
#pragma once

#include <stddef.h>
#include <stdint.h>

namespace wikipedia {
namespace fold_detail {

struct FoldPair {
  uint16_t from;
  uint16_t to;
};

// Sorted by `from`; every entry differs from its replacement.
inline constexpr FoldPair kTable[] = {
"""

CPP_TAIL = """};

inline constexpr size_t kTableSize = sizeof(kTable) / sizeof(kTable[0]);

inline bool inTableRange(uint32_t cp) {
  return (cp >= 0x00C0 && cp <= 0x024F) || (cp >= 0x0370 && cp <= 0x03FF) ||
         (cp >= 0x0400 && cp <= 0x04FF);
}

inline uint32_t lookup(uint32_t cp) {
  size_t lo = 0, hi = kTableSize;
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (kTable[mid].from < cp) {
      lo = mid + 1;
    } else {
      hi = mid;
    }
  }
  if (lo < kTableSize && kTable[lo].from == cp) {
    return kTable[lo].to;
  }
  return cp;
}

// Decodes one UTF-8 sequence at in[i]. Returns its length, or 0 for a byte
// that starts no valid sequence (the caller copies that byte through).
inline size_t decode(const char* in, size_t inLen, size_t i, uint32_t* cp) {
  unsigned char c = static_cast<unsigned char>(in[i]);
  size_t n;
  uint32_t v;
  if (c < 0x80) {
    *cp = c;
    return 1;
  } else if ((c & 0xE0) == 0xC0) {
    n = 2;
    v = c & 0x1F;
  } else if ((c & 0xF0) == 0xE0) {
    n = 3;
    v = c & 0x0F;
  } else if ((c & 0xF8) == 0xF0) {
    n = 4;
    v = c & 0x07;
  } else {
    return 0;
  }
  if (i + n > inLen) {
    return 0;
  }
  for (size_t k = 1; k < n; k++) {
    unsigned char cc = static_cast<unsigned char>(in[i + k]);
    if ((cc & 0xC0) != 0x80) {
      return 0;
    }
    v = (v << 6) | (cc & 0x3F);
  }
  *cp = v;
  return n;
}

inline size_t encode(uint32_t cp, char* out, size_t cap) {
  if (cp < 0x80) {
    if (cap < 1) return 0;
    out[0] = static_cast<char>(cp);
    return 1;
  } else if (cp < 0x800) {
    if (cap < 2) return 0;
    out[0] = static_cast<char>(0xC0 | (cp >> 6));
    out[1] = static_cast<char>(0x80 | (cp & 0x3F));
    return 2;
  } else if (cp < 0x10000) {
    if (cap < 3) return 0;
    out[0] = static_cast<char>(0xE0 | (cp >> 12));
    out[1] = static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
    out[2] = static_cast<char>(0x80 | (cp & 0x3F));
    return 3;
  }
  if (cap < 4) return 0;
  out[0] = static_cast<char>(0xF0 | (cp >> 18));
  out[1] = static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
  out[2] = static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
  out[3] = static_cast<char>(0x80 | (cp & 0x3F));
  return 4;
}

inline bool isFoldSpace(uint32_t cp) {
  return cp == ' ' || cp == '_' || (cp >= 0x09 && cp <= 0x0D);
}

inline bool isAscii(const char* in, size_t inLen) {
  for (size_t i = 0; i < inLen; i++) {
    if (static_cast<unsigned char>(in[i]) >= 0x80) return false;
  }
  return true;
}

}  // namespace fold_detail

// Folds a display title into its sort and lookup key. `in` need not be
// NUL-terminated and `out` is not NUL-terminated; *outLen is the bytes
// written. Stops at a character boundary when `out` is full.
inline void foldTitle(const char* in, size_t inLen, char* out, size_t outCap, size_t* outLen) {
  using namespace fold_detail;
  size_t o = 0;
  bool pendingSpace = false;
  if (isAscii(in, inLen)) {
    // 92% of titles: lowercase and the whitespace rule, byte by byte.
    for (size_t i = 0; i < inLen; i++) {
      unsigned char c = static_cast<unsigned char>(in[i]);
      if (isFoldSpace(c)) {
        if (o > 0) pendingSpace = true;
        continue;
      }
      if (o + (pendingSpace ? 1 : 0) + 1 > outCap) break;
      if (pendingSpace) {
        out[o++] = ' ';
        pendingSpace = false;
      }
      out[o++] = (c >= 'A' && c <= 'Z') ? static_cast<char>(c + 32) : static_cast<char>(c);
    }
    *outLen = o;
    return;
  }
  size_t i = 0;
  while (i < inLen) {
    uint32_t cp;
    size_t n = decode(in, inLen, i, &cp);
    if (n == 0) {
      // Not UTF-8: pass the byte through untouched, like any other symbol.
      if (pendingSpace) {
        if (o + 1 > outCap) break;
        out[o++] = ' ';
        pendingSpace = false;
      }
      if (o + 1 > outCap) break;
      out[o++] = in[i];
      i += 1;
      continue;
    }
    if (isFoldSpace(cp)) {
      if (o > 0) pendingSpace = true;
      i += n;
      continue;
    }
    if (cp >= 'A' && cp <= 'Z') {
      cp += 32;
    } else if (inTableRange(cp)) {
      cp = lookup(cp);
    }
    size_t need = (cp < 0x80) ? 1 : (cp < 0x800) ? 2 : (cp < 0x10000) ? 3 : 4;
    if (o + (pendingSpace ? 1 : 0) + need > outCap) break;
    if (pendingSpace) {
      out[o++] = ' ';
      pendingSpace = false;
    }
    o += encode(cp, out + o, outCap - o);
    i += n;
  }
  *outLen = o;
}

}  // namespace wikipedia
"""


def emit_cpp(table, path):
    lines = [CPP_HEAD]
    row = []
    for cp, r in table:
        row.append(f"{{0x{cp:04X}, 0x{r:04X}}}")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append(CPP_TAIL)
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines))


