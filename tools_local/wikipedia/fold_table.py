def emit_python(table, path):
    lines = [PY_HEAD % (WHITESPACE,), "TABLE = {"]
    for cp, r in table:
        lines.append(f'    "\\u{cp:04x}": "\\u{r:04x}",')
    lines.append("}")
    lines.append(PY_TAIL)
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines))


