#!/usr/bin/env python3
"""The title fold, defined once, emitted for both sides.

docs/apps/wikipedia-pack-format.md, "Sort key: the fold":

  1. "_" becomes a space; runs of whitespace collapse to one; leading and
     trailing spaces go.
  2. ASCII letters lowercase.
  3. Code points in Latin-1 Supplement, Latin Extended-A and B (U+00C0 to
     U+024F), Greek (U+0370 to U+03FF) and Cyrillic (U+0400 to U+04FF) map
     through the table: accents stripped to the base letter, then lowercased.
  4. Everything else passes through unchanged.

The table is derived here from Unicode data (the first code point of the
NFKD decomposition, then casefold when that is one code point, else lower,
else the base itself), so "É" and "é" both become "e", "ß" stays "ß", "Ω"
becomes "ω", "ς" becomes "σ". Whitespace for rule 1 is the six ASCII
whitespace characters and "_", spelled out rather than str.isspace() so the
device can do exactly the same thing with no Unicode tables. A replacement
that is whitespace or a control is refused (the code point passes through
instead), so rule 3 can never undo rule 1; so is one that is longer in
UTF-8 than what it replaces, so a fold is never longer than its input.

    python3 tools_local/wikipedia/fold_table.py

writes, next to this file, fold.py (the Python fold) and fold_vectors.tsv
(300 input/expected pairs), and src/apps_local/wikipedia/WikipediaFold.h
(the device fold). All three are committed; regenerate after editing this
file and commit the result. The device test and tests/test_fold.py both
read the vectors, which is what proves the two sides agree.
"""

import os
import random
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RANGES = ((0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x04FF))
WHITESPACE = " \t\n\r\x0b\x0c_"
VECTOR_COUNT = 300


def derive(cp):
    """The replacement for one code point, or None when it passes through."""
    ch = chr(cp)
    base = unicodedata.normalize("NFKD", ch)[0]
    cand = base.casefold()
    if len(cand) != 1:
        cand = base.lower()
    if len(cand) != 1:
        cand = base
    if cand == ch:
        return None
    if cand.isspace() or unicodedata.category(cand)[0] == "C":
        return None
    if len(cand.encode()) > len(ch.encode()):
        # U+023A and U+023E lowercase into Latin Extended-C, three UTF-8
        # bytes for two. Passing them through keeps the guarantee the C++
        # side is built on: a fold is never longer than its input.
        return None
    return ord(cand)


def build_table():
    table = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            r = derive(cp)
            if r is not None:
                table.append((cp, r))
    for cp, r in table:
        assert r < 0x10000, f"replacement for U+{cp:04X} is U+{r:04X}, outside the BMP"
        assert len(chr(r).encode()) <= len(chr(cp).encode()), (
            f"U+{cp:04X} -> U+{r:04X} grows in UTF-8; the C++ side assumes it never does"
        )
    return table


def fold_with(table_map, title):
    """The fold, written the way the C++ does it, so the vectors come from
    the same procedure the shipped module uses."""
    out = []
    pending = False
    for ch in title:
        if ch in WHITESPACE:
            if out:
                pending = True
            continue
        if pending:
            out.append(" ")
            pending = False
        o = ord(ch)
        if 0x41 <= o <= 0x5A:
            ch = chr(o + 32)
        elif o >= 0xC0:
            ch = table_map.get(ch, ch)
        out.append(ch)
    return "".join(out)


